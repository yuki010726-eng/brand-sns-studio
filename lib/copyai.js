/**
 * 모델에게 넘길 상품 사실 — 여기 없는 건 쓰면 안 된다.
 *
 * ⚠️ 이건 **재료**지 목차가 아니다. 처음엔 이 자료를 그대로 넘겼더니 모델이 주제를 제쳐두고
 * 자료를 순서대로 요약해 버렸다("기존 내용만 가져온다"). 그래서 각 항목 이름에
 * '재료', '베끼지 말 것'을 명시하고, 프롬프트에서 주제를 맨 앞에 세운다.
 */
function factSheet(p) {
  const proofs = (p.productProofs || [])
    .map((proof) => {
      if (typeof proof === "string") return `- ${proof}`;
      if (!proof || typeof proof !== "object") return "";
      const category = String(proof.category || proof.type || "").trim();
      const label = String(proof.label || "").trim();
      const value = String(proof.value ?? proof.content ?? "").trim();
      if (!value) return "";
      const head = [category, label].filter(Boolean).join(" · ");
      return `- ${head ? `[${head}] ` : ""}${value}`;
    })
    .filter(Boolean);
  const lines = [
    `상품명: ${p.name}`,
    proofs.length
      ? `[product_proofs] 아래 사실만 상품 정보의 근거로 사용합니다:\n${proofs.join("\n")}`
      : "[product_proofs] 확인된 상품 사실이 없습니다.",
    p.hashtags?.length
      ? `[출력용 해시태그] 필요한 채널에서는 아래 목록 안에서만 골라 사용합니다:\n${p.hashtags.map((tag) => `#${String(tag).replace(/^#/, "")}`).join(" ")}`
      : "",
  ];
  return lines.filter(Boolean).join("\n");
}

