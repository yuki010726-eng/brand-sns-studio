with expanded as (
  select
    pp.product_id,
    pp.id,
    pp.sort_order,
    item.value as content_item,
    item.ordinality
  from public.product_proofs pp
  cross join lateral jsonb_array_elements(pp.content)
    with ordinality as item(value, ordinality)
)
deduplicated as (
  select distinct on (product_id, content_item)
    product_id,
    content_item,
    sort_order,
    id,
    ordinality
  from expanded
  order by
    product_id,
    content_item,
    sort_order,
    id,
    ordinality
),
merged as (
  select
    product_id,
    jsonb_agg(
      content_item
      order by sort_order, id, ordinality
    ) as merged_content
  from deduplicated
  group by product_id
),
keepers as (
  select
    product_id,
    min(id) as keep_id
  from public.product_proofs
  group by product_id
)
update public.product_proofs pp
set content = m.merged_content
from merged m
join keepers k
  on k.product_id = m.product_id
where pp.id = k.keep_id;

-- 대표 행을 제외한 같은 product_id의 나머지 행 삭제

with keepers as (
  select
    product_id,
    min(id) as keep_id
  from public.product_proofs
  group by product_id
)
delete from public.product_proofs pp
using keepers k
where pp.product_id = k.product_id
  and pp.id <> k.keep_id;

