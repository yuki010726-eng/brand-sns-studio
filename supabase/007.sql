create policy "승인 사용자는 상품 근거 조회"
  on public.product_proofs
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.users
      where users.id = auth.uid()
        and users.status = 'approved'
    )
  );

drop type if exists public.product_content_type;

create table if not exists public.product_sources (

  id bigint generated by default as identity primary key,

  product_id text not null
    references public.products(id)
    on delete cascade,

  source_url text not null,

  source_content jsonb not null default '[]'::jsonb,

  created_at timestamptz not null default now(),

  constraint product_sources_content_array check (
    jsonb_typeof(source_content) = 'array'
    and jsonb_array_length(source_content) > 0
  ),
  
  constraint product_sources_product_url_key
    unique (product_id, source_url)

);

create index if not exists product_sources_product_idx
  on public.product_sources(product_id);

  alter table public.product_sources
  enable row level security;


